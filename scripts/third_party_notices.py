"""Generate THIRD_PARTY_NOTICES.md from the actual dependency metadata (not from memory).

Python: installed distributions in the project environment (runtime vs development from
`uv export`). Rust: `cargo metadata`. Lean: packages in lean/lake-manifest.json, license read
from each package's LICENSE file. Licenses that are not recognised as OSI approved are flagged.
"""

from __future__ import annotations

import json
import re
import subprocess
from importlib.metadata import distributions
from pathlib import Path

OSI = {  # SPDX ids / phrases treated as OSI approved
    "MIT",
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "MPL-2.0",
    "PSF-2.0",
    "Python-2.0",
    "Unicode-3.0",
    "Zlib",
    "LGPL-2.1",
    "LGPL-3.0",
    "0BSD",
    "Unlicense",
}
CLASSIFIER_MAP = {
    "MIT License": "MIT",
    "Apache Software License": "Apache-2.0",
    "BSD License": "BSD",
    "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0",
    "Python Software Foundation License": "PSF-2.0",
    "ISC License (ISCL)": "ISC",
}


NOTES = {  # reviewed by hand
    "CC0-1.0": "CC0-1.0 is a public-domain dedication (permissive, FSF-free) but not on the "
    "OSI list; numpy uses it for a bundled component. Compatible with MIT use.",
}


def osi_ok(expr: str) -> bool:
    expr = re.sub(r"\s+WITH\s+[A-Za-z0-9.\-]+", "", expr)  # exceptions only widen a license
    ids = [t for t in re.split(r"\s+(?:OR|AND)\s+|[()/]", expr) if t.strip()]
    return bool(ids) and all(t.strip() in OSI or t.strip() == "BSD" for t in ids)


def note(expr: str) -> str:
    return " ".join(v for k, v in NOTES.items() if k in expr)


def python_rows() -> list[tuple[str, str, str, str]]:
    runtime = set()
    exp = subprocess.run(
        ["uv", "export", "--no-dev", "--no-hashes", "--format", "requirements-txt"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    for line in exp.splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==", line)
        if m:
            runtime.add(m.group(1).lower().replace("_", "-"))
    rows = []
    for d in distributions():
        name = d.metadata["Name"]
        if name.lower() == "overthink":
            continue
        lic = d.metadata.get("License-Expression") or ""
        if not lic:
            cls = [
                c.split(" :: ")[-1]
                for c in d.metadata.get_all("Classifier") or []
                if c.startswith("License ::")
            ]
            lic = (
                " / ".join(CLASSIFIER_MAP.get(c, c) for c in cls)
                or (d.metadata.get("License") or "UNKNOWN").splitlines()[0][:60]
            )
        scope = "runtime" if name.lower().replace("_", "-") in runtime else "development"
        rows.append((name, d.version, lic, scope))
    return sorted(set(rows), key=lambda r: r[0].lower())


def rust_rows() -> list[tuple[str, str, str, str]]:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--manifest-path", "rust/Cargo.toml"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    )
    return sorted(
        (p["name"], p["version"], p.get("license") or "UNKNOWN", "build/runtime")
        for p in meta["packages"]
        if p["name"] != "overthink-core"
    )


def lean_rows() -> list[tuple[str, str, str, str]]:
    manifest = json.loads(Path("lean/lake-manifest.json").read_text())
    rows = [("Lean 4", Path("lean/lean-toolchain").read_text().strip(), "Apache-2.0", "toolchain")]
    for p in manifest["packages"]:
        lic_file = Path("lean/.lake/packages") / p["name"] / "LICENSE"
        text = lic_file.read_text()[:400] if lic_file.exists() else ""
        lic = (
            "Apache-2.0"
            if "Apache License" in text
            else "MIT"
            if "MIT License" in text or "Permission is hereby granted" in text
            else "UNKNOWN (check upstream)"
        )
        rows.append((p["name"], p.get("rev", "")[:12], lic, "Lean dependency"))
    return rows


def table(rows: list[tuple[str, str, str, str]]) -> list[str]:
    out = ["| Package | Version | License | Scope | OSI approved |", "|---|---|---|---|---|"]
    for name, ver, lic, scope in rows:
        flag = "yes" if osi_ok(lic) else ("**CHECK**: " + note(lic) if note(lic) else "**CHECK**")
        out.append(f"| {name} | {ver} | {lic} | {scope} | {flag} |")
    return out


def main() -> None:
    py, rs, ln = python_rows(), rust_rows(), lean_rows()
    flagged = [r for r in py + rs + ln if not osi_ok(r[2])]
    lines = [
        "# Third-party notices",
        "",
        (
            "Generated by `uv run python scripts/third_party_notices.py` from installed package "
            "metadata, `cargo metadata` and the Lean packages' LICENSE files. Do not edit by hand."
        ),
        "",
        (
            "This project's own code is MIT (see `LICENSE`); its datasets are CC BY 4.0 "
            "(`datasets/LICENSE`). OEIS data, if used, is CC BY-SA 4.0 and is never committed "
            "(downloaded at runtime into a git-ignored cache; see `src/overthink/conjecture/oeis.py`)."
        ),
        "",
        (
            f"Entries flagged **CHECK** ({len(flagged)}) have license metadata that this script "
            "could not map to an OSI-approved identifier; each must be checked by hand."
        ),
        "",
        "## Python",
        "",
        *table(py),
        "",
        "## Rust (crates compiled into `overthink._core`)",
        "",
        *table(rs),
        "",
        "## Lean",
        "",
        *table(ln),
        "",
    ]
    Path("THIRD_PARTY_NOTICES.md").write_text("\n".join(lines))
    print(f"python {len(py)}, rust {len(rs)}, lean {len(ln)}; flagged {len(flagged)}:")
    for r in flagged:
        print("  ", r)


if __name__ == "__main__":
    main()
