"""`overthink costs` and `overthink stats`: measured numbers for budget and progress reports.

Costs come only from recorded runs (dataset manifests, mining/falsification/pipeline/LLM run
records committed under experiments/). Nothing is estimated.
"""

from __future__ import annotations

import json
import re
import subprocess
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from overthink.data.schema import SCHEMAS
from overthink.registry.store import Registry


def _month_from_name(name: str) -> str | None:
    m = re.search(r"(\d{4})(\d{2})\d{2}T\d{6}Z", name)
    return f"{m.group(1)}-{m.group(2)}" if m else None


def cost_records(root: Path = Path(".")) -> list[dict[str, Any]]:
    recs: list[dict[str, Any]] = []
    for m in sorted((root / "datasets").glob("*/manifest.json")):
        d = json.loads(m.read_text())
        recs.append(
            {
                "experiment": "datasets",
                "item": f"generate {d['dataset']}",
                "month": d["generated_at"][:7],
                "seconds": d["generation_seconds"],
                "api_usd": 0.0,
            }
        )
    for p in sorted((root / "experiments").rglob("run.json")):
        if "experiments/runs" in str(p):
            continue
        d = json.loads(p.read_text())
        exp = p.relative_to(root / "experiments").parts[0]
        usage = d.get("proposer", {}).get("usage", {})
        recs.append(
            {
                "experiment": exp,
                "item": f"{'llm' if 'proposer' in d else 'mine'} {p.parent.name}",
                "month": _month_from_name(p.parent.name),
                "seconds": float(d.get("seconds", 0.0)),
                "api_usd": float(usage.get("api_cost_usd", 0.0)),
            }
        )
    for p in sorted((root / "experiments").rglob("falsify.json")):
        if "experiments/runs" in str(p):
            continue
        d = json.loads(p.read_text())
        exp = p.relative_to(root / "experiments").parts[0]
        recs.append(
            {
                "experiment": exp,
                "item": f"falsify {p.parent.name}",
                "month": _month_from_name(p.parent.name),
                "seconds": d["seconds"],
                "api_usd": 0.0,
            }
        )
    return recs


def write_costs(out: Path = Path("docs/costs.md")) -> dict[str, float]:
    recs = cost_records()
    by_exp: dict[str, list[float]] = defaultdict(lambda: [0.0, 0.0, 0])
    by_month: dict[str, list[float]] = defaultdict(lambda: [0.0, 0.0, 0])
    for r in recs:
        for key, table in ((r["experiment"], by_exp), (r["month"] or "unknown", by_month)):
            table[key][0] += r["seconds"]
            table[key][1] += r["api_usd"]
            table[key][2] += 1
    total_s = sum(r["seconds"] for r in recs)
    total_usd = sum(r["api_usd"] for r in recs)
    lines = [
        "# Compute and API costs (measured)",
        "",
        f"Generated by `overthink costs` on {datetime.now(UTC).date()} from recorded runs only.",
        (
            "Compute is wall-clock time of the recorded pipeline steps on the author's laptop "
            "(Apple M4, 10 cores, 24 GB). Not included: Lean builds, development and test runs, "
            "and exploratory one-off analyses."
        ),
        "",
        (
            f"**Total: {total_s / 60:.1f} min of recorded compute, ${total_usd:.2f} API spend, "
            f"{len(recs)} recorded steps.**"
        ),
        "",
        "## By experiment",
        "",
        "| Experiment | Steps | Compute (s) | API (USD) |",
        "|---|---|---|---|",
        *[f"| {k} | {v[2]:.0f} | {v[0]:.1f} | {v[1]:.2f} |" for k, v in sorted(by_exp.items())],
        "",
        "## By month",
        "",
        "| Month | Steps | Compute (s) | API (USD) |",
        "|---|---|---|---|",
        *[f"| {k} | {v[2]:.0f} | {v[0]:.1f} | {v[1]:.2f} |" for k, v in sorted(by_month.items())],
        "",
    ]
    out.write_text("\n".join(lines))
    return {"compute_seconds": total_s, "api_usd": total_usd}


def _lean_theorems(root: Path = Path("lean/OverthinkLean")) -> dict[str, int]:
    counts = {"hand_written": 0, "generated": 0}
    for f in root.rglob("*.lean"):
        n = len(re.findall(r"^theorem ", f.read_text(), flags=re.MULTILINE))
        counts["generated" if "Generated" in f.parts else "hand_written"] += n
    return counts


def write_stats(out: Path = Path("docs/metrics.md")) -> dict[str, Any]:
    state = Registry().state()
    by_status: dict[str, int] = defaultdict(int)
    by_proposer: dict[str, int] = defaultdict(int)
    for e in state.values():
        by_status[e["status"]] += 1
        by_proposer["llm" if e["conjecture"]["method"].startswith("llm:") else "classical"] += 1
    rows = 0
    datasets = []
    for m in sorted(Path("datasets").glob("*/manifest.json")):
        d = json.loads(m.read_text())
        rows += d["row_count"]
        datasets.append(f"{d['dataset']} ({d['row_count']:,} rows)")
    lean = _lean_theorems()
    releases = subprocess.run(
        ["git", "tag", "-l", "v*"], capture_output=True, text=True, check=False
    ).stdout.split()
    stats = {
        "game_families": len(SCHEMAS),
        "dataset_rows": rows,
        "conjectures_proposed": len(state),
        "by_proposer": dict(by_proposer),
        "by_status": dict(by_status),
        "lean_theorems": lean,
        "dataset_releases": len(releases),
    }
    lines = [
        "# Project metrics",
        "",
        (
            f"Generated by `overthink stats` on {datetime.now(UTC).date()} from the registry, "
            "dataset manifests and Lean sources."
        ),
        "",
        "| Metric | Value |",
        "|---|---|",
        (
            f"| Game families with exact solvers and datasets | {len(SCHEMAS)} "
            f"({', '.join(sorted(SCHEMAS))}) |"
        ),
        f"| Dataset rows (Grundy values or P-positions) | {rows:,} |",
        (
            f"| Conjectures proposed | {len(state):,} (classical {by_proposer['classical']:,}, "
            f"LLM {by_proposer['llm']:,}) |"
        ),
        f"| Refuted | {by_status['refuted']:,} |",
        f"| Surviving 10x falsification, not proved | {by_status['survived']:,} |",
        f"| Matched to published work (`known`) | {by_status['known']:,} |",
        f"| Proved in Lean (registry entries) | {by_status['proved']:,} |",
        (
            f"| Lean theorems: hand-written / generated | {lean['hand_written']} / "
            f"{lean['generated']} |"
        ),
        f"| Dataset releases (git tags v*) | {len(releases)} |",
        "",
        (
            "**Reading these numbers.** Registry entries are not distinct results: for example, "
            "139 proved entries are instances of one finite-window lemma. Most proved statements "
            "are known or elementary. The one result that may be new (the P-positions of "
            "W({a,a+1}) for every a) is described in `docs/results/W_pair_theorem.md`."
        ),
        "",
        "Datasets: " + "; ".join(datasets) + ".",
        "",
    ]
    out.write_text("\n".join(lines))
    return stats
