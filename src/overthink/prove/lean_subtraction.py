"""Export surviving subtraction-game periodicity conjectures to Lean, build, and record proofs.

Every registry conjecture of the form "g_S(n + p) = g_S(n) for all n >= n0" (kind `periodic`,
grouped view grundy~n, raw) becomes one Lean theorem per subtraction set in its scope (the
set it was mined from plus its aliases). Each is proved by `periodic_of_window` with the
finite window checked by kernel `decide` (see lean/OverthinkLean/Subtraction.lean). The axiom
check rejects `sorryAx` and `Lean.ofReduceBool` (native_decide).

A conjecture is marked `proved` only if the theorems for *every* set in its scope compile.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Any

from overthink.registry.store import Registry

LEAN_DIR = Path("lean")
MODULE = "OverthinkLean.Generated.SubtractionPeriodicity"
LEAN_FILE = LEAN_DIR / "OverthinkLean" / "Generated" / "SubtractionPeriodicity.lean"
ALLOWED_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}
METHOD = "general: periodic_of_window + finite window by kernel decide"


def _targets(registry: Registry) -> list[dict[str, Any]]:
    out = []
    for cid, e in sorted(registry.state().items()):
        c = e["conjecture"]
        meta = c.get("sequence_meta", {})
        proved_here = e["status"] == "proved" and any(
            h.get("type") == "proved" and h.get("method") == METHOD for h in e["history"]
        )
        is_target = (
            c["kind"] == "periodic"
            and meta.get("dataset", "").startswith("subtraction")
            and meta.get("view") == "grouped"
            and meta.get("target") == "grundy"
            and meta.get("transform") == "raw"
        )
        if not is_target or (e["status"] != "survived" and not proved_here):
            continue
        fals = [h for h in e["history"] if h.get("type") == "falsification"]
        scope = [p["sequence_id"] for p in fals[-1]["per_sequence"]]
        sets = [
            tuple(int(x) for x in re.search(r"subtraction_set=([\d,]+)", sid).group(1).split(","))
            for sid in scope
        ]
        out.append(
            {
                "conjecture_id": cid,
                "period": c["params"]["period"],
                "n0": c["params"]["n0"],
                "sets": sets,
                "already_proved": proved_here,
            }
        )
    return out


def _theorem_name(s: tuple[int, ...]) -> str:
    return "sub_" + "_".join(map(str, s))


def render(targets: list[dict[str, Any]]) -> str:
    lines = [
        "-- SPDX-License-Identifier: MIT",
        "import OverthinkLean.Subtraction",
        "",
        "/-! Generated by `overthink prove` from the conjecture registry. Do not edit.",
        "",
        "Each theorem: the Grundy sequence of the subtraction game with set `S` satisfies",
        "`g (n + p) = g n` for all `n ≥ n₀`, as proposed by the pipeline and survived at 10x.",
        f"Proof method: {METHOD}. -/",
        "",
        "namespace Overthink.Subtraction.Generated",
        "",
    ]
    for t in targets:
        for s in t["sets"]:
            lst = "[" + ", ".join(map(str, s)) + "]"
            lines += [
                (
                    f"/-- {t['conjecture_id']}: S = {{{', '.join(map(str, s))}}}, "
                    f"period {t['period']} from n = {t['n0']}. -/"
                ),
                f"theorem {_theorem_name(s)} :",
                f"    ∀ n, {t['n0']} ≤ n → grundy {lst} (n + {t['period']}) = grundy {lst} n :=",
                f"  periodic_of_window (m := {max(s)}) (n₀ := {t['n0']}) (by decide) (by",
                "    intro n h1 h2",
                "    simp only [grundy_eq_table]",
                "    interval_cases n <;> decide)",
                "",
            ]
    lines.append("end Overthink.Subtraction.Generated")
    return "\n".join(lines) + "\n"


def _lake(*args: str, timeout: int = 7200) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["lake", *args], cwd=LEAN_DIR, capture_output=True, text=True, timeout=timeout, check=False
    )


def run(registry: Registry, record: bool = True) -> dict[str, Any]:
    targets = _targets(registry)
    LEAN_FILE.parent.mkdir(parents=True, exist_ok=True)
    LEAN_FILE.write_text(render(targets))
    build = _lake("build", MODULE)
    if build.returncode != 0:
        tail = (build.stdout + build.stderr)[-4000:]
        return {"ok": False, "targets": len(targets), "build_log_tail": tail}
    names = [_theorem_name(s) for t in targets for s in t["sets"]]
    check = LEAN_DIR / "CheckGenerated.lean"
    check.write_text(
        f"import {MODULE}\n"
        + "".join(f"#print axioms Overthink.Subtraction.Generated.{n}\n" for n in names)
    )
    out = _lake("env", "lean", check.name)
    check.unlink()
    axioms = re.findall(r"depends on axioms: \[([^\]]*)\]", out.stdout)
    bad = [a for a in axioms if not {x.strip() for x in a.split(",")} <= ALLOWED_AXIOMS]
    if (
        out.returncode != 0
        or len(axioms) + out.stdout.count("does not depend") != len(names)
        or bad
    ):
        return {"ok": False, "targets": len(targets), "axiom_check": out.stdout[-2000:]}
    toolchain = (LEAN_DIR / "lean-toolchain").read_text().strip()
    manifest = json.loads((LEAN_DIR / "lake-manifest.json").read_text())
    mathlib = next(p["rev"] for p in manifest["packages"] if p["name"] == "mathlib")
    if record:
        registry.append(
            [
                {
                    "type": "proved",
                    "conjecture_id": t["conjecture_id"],
                    "method": METHOD,
                    "lean_module": MODULE,
                    "lean_theorems": [_theorem_name(s) for s in t["sets"]],
                    "lean_toolchain": toolchain,
                    "mathlib_rev": mathlib,
                }
                for t in targets
                if not t["already_proved"]
            ]
        )
    return {
        "ok": True,
        "targets": len(targets),
        "theorems": len(names),
        "lean_toolchain": toolchain,
        "mathlib_rev": mathlib,
    }
